"""Mistake Detective benchmark: score the detector on tests/data/detective_corpus.json.

    python tools/evaluate_detective.py               # print the report
    python tools/evaluate_detective.py --write-doc   # also regenerate docs/EVALUATION.md

This is an internal regression benchmark, not a scientific accuracy claim: the corpus is
small, written for this project, and its labels follow Pi Core's documented conventions.
"""
import json
import statistics
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from picore.engine.checker import BAD, OK, SUPPORTED, UNSURE, WARN, judge_step  # noqa: E402

CORPUS = ROOT / "tests" / "data" / "detective_corpus.json"
VERDICT = {OK: "correct", BAD: "mistake", WARN: "warning", UNSURE: "unknown", SUPPORTED: "supported"}
FLAGGED = {"mistake", "warning"}


def load(path=CORPUS):
    return json.loads(Path(path).read_text(encoding="utf-8"))["cases"]


def rule_matches(expected, got):
    """calculus.derivative is a family: the detector reports the specific mistake (calculus.chain_missing, ...)."""
    if not expected:
        return False
    if expected == "calculus.derivative":
        return got.startswith("calculus.") and got not in ("calculus.wrong_variable", "calculus.antiderivative_domain")
    return got == expected


def run(cases):
    rows = []
    for c in cases:
        t = time.perf_counter()
        try:
            j = judge_step(c["previous"], c["student"], c.get("label", ""))
            got, rule, kind, err = VERDICT[j.verdict], j.rule, j.rule_kind, ""
        except Exception as exc:                       # an exception is itself a benchmark failure
            got, rule, kind, err = "error", "", "", f"{type(exc).__name__}: {exc}"
        rows.append(dict(case=c, got=got, rule=rule, rule_kind=kind, error=err, seconds=time.perf_counter() - t))
    return rows


def score(rows):
    m = Counter()
    problems = defaultdict(list)
    for r in rows:
        c, got = r["case"], r["got"]
        exp = c["expected_verdict"]
        m["total"] += 1
        if got == "error":
            problems["errors"].append(r)
            continue
        if exp == "correct":
            m["negatives"] += 1
            if got in FLAGGED:
                m["FP"] += 1
                problems["false positives (correct work flagged)"].append(r)
            else:
                m["TN"] += 1
                m["proved_correct"] += got == "correct"
        elif exp in FLAGGED:
            m["positives"] += 1
            if got in FLAGGED:
                m["TP"] += 1
                if c.get("expected_rule"):
                    m["with_expected_rule"] += 1
                    if rule_matches(c["expected_rule"], r["rule"]):
                        m["rule_correct"] += 1
                    elif r["rule"] and r["rule_kind"] == "misconception":
                        m["misattributed"] += 1
                        problems["misattributions (wrong misconception named)"].append(r)
                    else:
                        m["rule_missing"] += 1
                        problems["detected, but the expected rule was not named"].append(r)
                if c.get("must_not_name_rule") and r["rule"] and r["rule_kind"] == "misconception":
                    m["invented"] += 1
                    problems["invented diagnosis (must not name a rule)"].append(r)
            else:
                m["FN"] += 1
                problems["missed (wrong step not flagged)"].append(r)
        elif exp == "unknown":
            m["unknowns"] += 1
            if got in ("unknown", "supported"):
                m["unknown_honest"] += 1
            else:
                m["unknown_overclaim"] += 1
                problems["overclaimed (expected 'unknown')"].append(r)
        m["exact_verdict"] += (got == exp) or (exp == "unknown" and got == "supported")
    tp, fp, fn = m["TP"], m["FP"], m["FN"]
    m["precision"] = tp / (tp + fp) if tp + fp else 1.0
    m["recall"] = tp / (tp + fn) if tp + fn else 1.0
    m["fp_rate"] = fp / m["negatives"] if m["negatives"] else 0.0
    times = sorted(r["seconds"] for r in rows)
    m["median_s"] = statistics.median(times)
    m["p95_s"] = times[int(0.95 * (len(times) - 1))]
    m["max_s"] = times[-1]
    return m, problems


def report(m, problems, rows):
    pct = lambda x: f"{100 * x:.1f}%"
    kinds = Counter(r["case"]["kind"] for r in rows)
    cats = Counter(r["case"]["category"] for r in rows)
    lines = [
        "# Mistake Detective evaluation",
        "",
        "Generated by `python tools/evaluate_detective.py --write-doc` from "
        "[`tests/data/detective_corpus.json`](../tests/data/detective_corpus.json). "
        "`tests/test_detective_corpus.py` fails if the guarantees below regress.",
        "",
        "> **This is an internal regression benchmark, not a scientific accuracy claim.** The corpus is "
        f"{m['total']} single-step cases written for this project (most generated from the mathematics and "
        "then reviewed against SymPy; the domain set written by hand). It is small, not drawn from real "
        "students, and labelled under Pi Core's documented conventions (log = ln, radians, real solutions, "
        "other letters constant under d/dx). Relabelled cases carry a `relabel` field explaining why.",
        "",
        "## Corpus",
        "",
        "| By kind | Cases | | By category | Cases |",
        "|---|---|---|---|---|",
    ]
    kk, cc = sorted(kinds.items()), sorted(cats.items())
    for i in range(max(len(kk), len(cc))):
        a = kk[i] if i < len(kk) else ("", "")
        b = cc[i] if i < len(cc) else ("", "")
        lines.append(f"| {a[0]} | {a[1]} | | {b[0]} | {b[1]} |")
    lines += [
        "",
        "Kinds: **positive** = a wrong step from the catalogue; **negative** = a correct step that must not be "
        "flagged; **adversarial** = built to fool a pattern matcher; **ambiguous** = the cause or the validity "
        "cannot be pinned down, so Pi Core must not invent a diagnosis.",
        "",
        "## Results",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| **False positives on correct work** | **{m['FP']} of {m['negatives']} ({pct(m['fp_rate'])})** |",
        f"| Correct steps proved correct (rest: 'numerically supported' / 'couldn't check') | {m['proved_correct']} of {m['negatives']} |",
        f"| Wrong steps flagged (recall) | {m['TP']} of {m['positives']} ({pct(m['recall'])}) |",
        f"| Precision of a flag | {pct(m['precision'])} |",
        f"| Expected misconception named exactly | {m['rule_correct']} of {m['with_expected_rule']} |",
        f"| **Misattributions** (a different misconception named) | **{m['misattributed']}** |",
        f"| **Invented diagnoses** (a cause named where none should be) | **{m['invented']}** |",
        f"| 'Unknown' cases answered honestly (not claimed right or wrong) | {m['unknown_honest']} of {m['unknowns']} |",
        f"| Verdict matches the label exactly | {m['exact_verdict']} of {m['total']} |",
        f"| Errors (exceptions) | {len(problems.get('errors', []))} |",
        f"| Latency per step: median / p95 / max | {m['median_s']*1000:.0f} ms / {m['p95_s']*1000:.0f} ms / {m['max_s']*1000:.0f} ms |",
        "",
        "Definitions: a step is *flagged* when the verdict is 'mistake here' or 'check needed'. Descriptive "
        "findings (wrong coefficients, lost domain) state *what* is wrong without naming a cause, so they never "
        "count as invented or misattributed diagnoses.",
        "",
        "## Remaining differences",
        "",
    ]
    if not any(problems.values()):
        lines.append("None.")
    for title, items in problems.items():
        if not items:
            continue
        lines += [f"### {title} ({len(items)})", "", "| Case | Step | Expected | Pi Core |", "|---|---|---|---|"]
        for r in items:
            c = r["case"]
            step = f"`{c['previous']}` → {'[' + c['label'] + '] ' if c.get('label') else ''}`{c['student']}`"
            exp = c["expected_verdict"] + (f" ({c['expected_rule']})" if c.get("expected_rule") else "")
            got = r["got"] + (f" ({r['rule']})" if r["rule"] else "") + (f" {r['error']}" if r["error"] else "")
            lines.append(f"| {c['id']} | {step.replace('|', '¦')} | {exp} | {got} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    rows = run(load())
    m, problems = score(rows)
    text = report(m, problems, rows)
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)
    if "--write-doc" in sys.argv:
        (ROOT / "docs" / "EVALUATION.md").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
